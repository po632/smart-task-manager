create table if not exists tasks (
  id bigint generated by default as identity primary key,
  title text not null,
  priority text not null default '中',
  done boolean not null default false,
  created_at timestamptz not null default now()
);

alter table tasks enable row level security;
create policy "anon read tasks"   on tasks for select using (true);
create policy "anon insert tasks" on tasks for insert with check (true);
create policy "anon update tasks" on tasks for update using (true) with check (true);
create policy "anon delete tasks" on tasks for delete using (true);
